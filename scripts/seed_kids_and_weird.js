async function seed() {
  console.log('Seeding kids stories and weird news to Supabase...');
  
  // 1. Kids stories
  for (const story of KIDS_STORIES) {
    const { data: existing } = await supabase
      .from('articles')
      .select('id')
      .eq('slug', story.slug)
      .maybeSingle();

    if (!existing) {
      const { error } = await supabase.from('articles').insert({
        ...story,
        published_at: new Date().toISOString(),
        created_at: new Date().toISOString()
      });
      if (error) console.error(`Error saving kids story ${story.slug}:`, error.message);
      else console.log(`Saved kids story: ${story.title}`);
    } else {
      console.log(`Kids story already exists: ${story.slug}`);
    }
  }

  // 2. Weird news
  for (const story of WEIRD_STORIES) {
    const { data: existing } = await supabase
      .from('articles')
      .select('id')
      .eq('slug', story.slug)
      .maybeSingle();

    if (!existing) {
      const { error } = await supabase.from('articles').insert({
        ...story,
        published_at: new Date().toISOString(),
        created_at: new Date().toISOString()
      });
      if (error) console.error(`Error saving weird story ${story.slug}:`, error.message);
      else console.log(`Saved weird story: ${story.title}`);
    } else {
      console.log(`Weird story already exists: ${story.slug}`);
    }
  }

  console.log('Seeding completed successfully!');
}

